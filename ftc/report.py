"""A pipeline's final output: final_report.json (docs/spec_and_io.md §3.7) and a short model_card.md.

Written by scripts/run_pipeline.py (no agents) and by skills/finetune-report (agent mode), so both modes
produce the same files. Stdlib only.
"""
import json
from datetime import date
from pathlib import Path

from .pipeline import _atomic_write, now_iso

SYSTEMS = [("tuned", "Fine-tuned"), ("base_fewshot", "Base model, few-shot prompt"),
           ("base_zeroshot", "Base model, zero-shot"), ("teacher", "Teacher (ceiling)")]


def _read(path) -> dict:
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError, TypeError):
        return {}


def dev_history(pl, upto: int) -> list:
    """Tuned dev score per loop, from loops/<n>/eval/eval_report.json."""
    hist = []
    for n in range(1, upto + 1):
        r = _read(pl.loop_dir(n) / "eval" / "eval_report.json")
        if r.get("systems"):
            hist.append({"loop": n, "tuned": r["systems"].get("tuned", {}).get("score")})
    return hist


def _fmt(x):
    return "–" if x is None else f"{x:.3f}"


def model_card(spec: dict, final: dict, run: dict) -> str:
    cfg = run.get("config") or {}
    base = run.get("base_model") or cfg.get("model") or (spec.get("models") or {}).get("student") or "the base model"
    ho = final.get("heldout") or {}
    lines = [f"# {spec.get('title') or 'Fine-tuned model'}: LoRA adapter for {base}", "",
             spec.get("task") or "", "",
             f"- **Adapter:** `{final['adapter_path']}`" + (f" ({final['hub_url']})" if final.get("hub_url") else ""),
             f"- **Base model:** {base}",
             f"- **Training run:** `{final.get('train_job_id')}`, loop {final.get('best_loop')} of pipeline "
             f"`{final.get('pipeline_id')}`. LoRA r={cfg.get('rank', '?')}, alpha={cfg.get('alpha', '?')}, "
             f"lr={cfg.get('lr', '?')}, epochs={cfg.get('epochs', '?')}",
             f"- **Reply format:** {spec.get('io_format') or '–'}", "",
             "## Held-out results (scored once, at the end)", "", "| System | Score | 95% CI |", "|---|---|---|"]
    for key, label in SYSTEMS:
        s = (ho.get("systems") or {}).get(key)
        if s:
            ci = s.get("ci95") or [None, None]
            lines.append(f"| {label} | {_fmt(s.get('score'))} | {_fmt(ci[0])} – {_fmt(ci[1])} |")
    by_src = ho.get("by_source") or []
    if by_src:
        lines += ["", "By source (real examples vs generated ones):", "", "| Source | n | Base few-shot | Tuned |", "|---|---|---|---|"]
        lines += [f"| {b.get('source')} | {b.get('n', '–')} | {_fmt(b.get('base_fewshot'))} | {_fmt(b.get('tuned'))} |"
                  for b in by_src]
    hist = final.get("dev_history") or []
    if hist:
        lines += ["", "## Dev score per loop", "", "| Loop | Tuned |", "|---|---|"]
        lines += [f"| {h['loop']} | {_fmt(h.get('tuned'))} |" for h in hist]
    lines += ["", "## Limitations", "",
              "- The training data was generated by an LLM from the task spec, and most of the benchmark too. A score on "
              "generated items can partly reward the generator's style; the `real` rows above (if any) are the honest check.",
              f"- Made automatically by the finetuner pipeline on {date.today().isoformat()}.", ""]
    return "\n".join(lines)


def write_final(out_dir, *, pipeline_id, best_adapter, best_job, best_loop, heldout: dict, history: list,
                spec: dict) -> dict:
    """Write final_report.json + model_card.md into out_dir and return the report. The best run's
    metrics.json / run.json (next to its adapter) supply hub_url, base model and LoRA settings."""
    out_dir = Path(out_dir)
    run_dir = Path(best_adapter).parent if best_adapter else None
    run = {**_read(run_dir / "metrics.json"), **_read(run_dir / "run.json")} if run_dir else {}
    final = {"pipeline_id": pipeline_id, "best_loop": best_loop, "train_job_id": best_job,
             "adapter_path": best_adapter, "hub_url": run.get("hub_url"), "infinite_post_url": None,
             "heldout": {"systems": heldout.get("systems"), "by_source": heldout.get("by_source")},
             "dev_history": history, "model_card_path": str(out_dir / "model_card.md"), "created_at": now_iso()}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model_card.md").write_text(model_card(spec or {}, final, run))
    _atomic_write(out_dir / "final_report.json", final)
    return final
